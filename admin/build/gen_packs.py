#!/usr/bin/env python3
"""Generates /packs/ — review packs: one continuous page each, and a PDF printed from it.

Run from anywhere: python3 admin/build/gen_packs.py
Figures are captured separately by admin/build/gen_pack_figures.py (Chromium), which is
slow and is not run on every build; the pack falls back to a stated absence if a figure
is missing rather than shipping a blank box.

From brief 21. The defining property of a pack is that IT CONTROLS THE SEQUENCE. A website
cannot: its hyperlink nature means nobody knows what a reviewer saw or in what order. A pack
is a selection in a fixed order, readable end to end with no link followed, and because a PDF
is not modifiable it survives as a record better than a page does.

A pack is NOT the book. Every cover says so.

Adding a pack: write a build_<slug>() returning (meta, body_html), add it to PACKS, run this.
"""
import hashlib
import json
import subprocess
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
VERSION = (ROOT / "admin/build/version.txt").read_text().strip()
OUT = ROOT / "v2" / "packs"
FIG = OUT / "figures"
TODAY = date.today().strftime("%-d %B %Y")


def load(rel):
    p = ROOT / rel
    raw = p.read_bytes()
    return json.loads(raw), hashlib.sha256(raw).hexdigest()


def esc(t):
    return (str(t).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))


BANNED = "relates-to"


def fmt(t):
    """The house inline grammar, the same one the site's data carries. The banned generic
    edge is marked wherever it appears, because a pack quotes the ban and the tripwire
    cannot tell a quotation from a use."""
    import re
    s = esc(t)
    s = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", s)
    s = re.sub(r"`([^`]+)`", r"<code>\1</code>", s)
    return mark_banned(s)


def mark_banned(s):
    import re
    return re.sub(r"(?<!-verb=\"\")\b" + BANNED + r"\b",
                  f'<code data-banned-verb="">{BANNED}</code>', s)


def figure(name, caption, why):
    """A figure with a caption that carries its own point, because a pack must read with
    no link followed. A missing figure states its absence rather than leaving a hole."""
    f = FIG / name
    if not f.exists():
        return (f'<figure><figcaption><b>Figure not captured.</b> {esc(caption)} '
                f'It is generated by <code>gen_pack_figures.py</code>, which needs a browser '
                f'and is not run on every build. Its absence is stated rather than hidden.'
                f'</figcaption></figure>')
    return (f'<figure><img src="figures/{name}" alt="{esc(caption)}">'
            f'<figcaption><b>{esc(caption)}</b> {esc(why)}</figcaption></figure>')


# --------------------------------------------------------------- pack 1 ----
def build_concepts_and_evidence():
    alt, alt_sha = load("v1/altitudes/data/altitudes.json")
    docs, docs_sha = load("v1/docs/data/docs.json")
    dec, dec_sha = load("decisions/data/decisions.json")
    peaks = set(alt["peaks"])
    h = []

    h.append('<h2 id="how">How to read this</h2>')
    h.append('<p>Seven sections, in a fixed order, and the order is the argument: the '
             '<b>vocabulary</b> first, then <b>which of it the corpus actually carries</b>, then '
             '<b>what the material disagrees with itself about</b>, then <b>what is unanswered</b>. '
             'Nothing here needs a link followed. Every table stands alone and every figure has a '
             'caption that carries its point.</p>')
    h.append('<p>What you are being asked to decide is at the end, numbered. The short version: '
             '<b>is this the vocabulary of the book you intend to write?</b> Everything else in '
             'this pack exists to make that question answerable.</p>')

    # 1. the concepts
    h.append('<h2 class="packsec" id="concepts">1. The vocabulary</h2>')
    h.append(f'<p>{len(alt["concepts"])} concepts, each with a definition, what it is also called, '
             'and <b>what it is near but importantly not</b>. That last column is the one that does '
             'the work: a definition says what a thing is, and a near-but-not says which '
             'neighbouring idea a reader will otherwise substitute for it.</p>')
    h.append(figure("concepts.png", "The concept map, all twenty-four.",
                    "Gold borders are the computed peaks. The clustering is not laid out by hand: "
                    "it is force over the declared edges, so a concept that sits alone sits alone "
                    "in the corpus too."))
    for c in sorted(alt["concepts"], key=lambda x: (-x["strength"]["score"], x["label"])):
        h.append(f'<h3>{esc(c["label"])}'
                 + (' <span class="packpeak">peak</span>' if c["id"] in peaks else '')
                 + f' <span class="packalso">strength {c["strength"]["score"]}</span></h3>')
        h.append(f'<p class="packdef">{fmt(c["definition"])}</p>')
        if c.get("also_called"):
            h.append(f'<p class="packalso"><b>Also called:</b> {mark_banned(esc(", ".join(c["also_called"])))}</p>')
        if c.get("near_but_not"):
            h.append('<p class="packalso"><b>Near but not:</b> '
                     + mark_banned(esc("; ".join(c["near_but_not"]))) + '</p>')

    # 2. the peaks
    h.append('<h2 class="packsec" id="peaks">2. The peaks, and the formula that found them</h2>')
    h.append('<p>These were computed, not chosen. Disagree by disagreeing with the formula, which '
             'is one line and is printed here so it can be argued with:</p>')
    h.append('<code class="packrule">strength = outward edges + 2 &times; inward edges + units '
             'carrying it + 2 &times; published demonstrations</code>')
    h.append('<table><thead><tr><th>Concept</th><th>Strength</th><th>Why it scores</th></tr></thead><tbody>')
    for pid in alt["peaks"]:
        c = [x for x in alt["concepts"] if x["id"] == pid][0]
        s = c["strength"]
        h.append(f'<tr><td><b>{esc(c["label"])}</b></td><td>{s["score"]}</td>'
                 f'<td class="packalso">{s.get("out", 0)} out, {s.get("incoming", 0)} in, '
                 f'{s.get("units", 0)} units, {s.get("demonstrations", 0)} demonstrations</td></tr>')
    h.append('</tbody></table>')
    h.append('<p><b>One peak is uncomfortable and is kept.</b> <em>Schema-first thinking</em> is the '
             'position this book exists to argue against, and it scores as one of the strongest '
             'nodes, because five separate concepts define themselves partly by opposing it. It was '
             'not tuned away. The caution it carries: a strongly connected node is not a '
             'well-supported one, and any ranking that conflates connectivity with evidence will '
             'overstate whatever the book repeats most often.</p>')

    # 3. the corpus, measured
    h.append('<h2 class="packsec" id="measured">3. What the corpus actually carries</h2>')
    t = docs["totals"]
    h.append(f'<p>{t["docs"]} source documents, {t["words"]:,} words, carried byte for byte with '
             f'their hashes. Each was measured against the vocabulary mechanically: every concept '
             f'declares a phrase list, the build counts occurrences, and the phrase list is '
             f'published so the measurement can be disputed. {t["concepts"]} of the '
             f'{len(alt["concepts"])} concepts appear at all.</p>')
    h.append(figure("docs-all.png", "All twenty-one sources, joined by the concepts they share.",
                    "Purple is a document, green a concept. The documents were written months "
                    "apart for different audiences; nothing joins them here but the concepts they "
                    "were independently measured to contain."))
    h.append('<h3>Concentration: breadth of mention is not weight</h3>')
    h.append('<p>A concept mentioned in every document is not the same as a concept carried by '
             'every document. Concentration is the share of a concept\'s total mentions sitting in '
             'its top three documents. High means a couple of documents do the work and the rest '
             'allude to it.</p>')
    h.append('<table><thead><tr><th>Concept</th><th>In</th><th>Mentions</th><th>Conc.</th>'
             '<th>Carried mostly by</th></tr></thead><tbody>')
    for c in docs["common"][:12]:
        top = ", ".join(f'{x["slug"]} ({x["n"]})' for x in c["top"])
        h.append(f'<tr><td>{esc(c["label"])}</td><td>{c["n"]}/{t["docs"]}</td><td>{c["total"]}</td>'
                 f'<td>{c["concentration"]:.2f}</td><td class="packalso">{esc(top)}</td></tr>')
    h.append('</tbody></table>')
    spread = sorted(docs["common"], key=lambda x: x["concentration"])
    h.append(f'<p><b>Only two concepts come in under 0.55.</b> The most distributed is '
             f'<em>{esc(spread[0]["label"])}</em> at {spread[0]["concentration"]:.2f}. Everything '
             f'else sits above 0.7, which is the caution to carry into any claim that the corpus '
             f'is "about" a given idea.</p>')

    # 4. the inventory
    h.append('<h2 class="packsec" id="inventory">4. What the first edition reduces to</h2>')
    inv = alt["inventory"]
    h.append(f'<table><thead><tr><th>Kind</th><th>Count</th></tr></thead><tbody>'
             f'<tr><td>Facts, meaning claims with resolving evidence</td><td>{inv["fact"]}</td></tr>'
             f'<tr><td>Assertions, meaning claims argued but not evidenced</td><td>{inv["assertion"]}</td></tr>'
             f'<tr><td>Opinions, meaning claims stated as preference</td><td>{inv["opinion"]}</td></tr>'
             f'<tr><td>Measured cross-references between chapters</td><td>{inv["cites"]}</td></tr>'
             f'</tbody></table>')
    h.append(f'<p>{fmt(inv["note"])}</p>')

    # 5. findings
    h.append('<h2 class="packsec" id="findings">5. Where the material disagrees with itself</h2>')
    op = sum(1 for f in alt["findings"] if f["state"] == "open")
    h.append(f'<p>{len(alt["findings"])} findings, {op} still open. A finding is not a defect to be '
             'tidied away: a contradiction can be correct in context, and the point of making them '
             'detectable is that they can then be argued about rather than discovered by a reader.</p>')
    for f in alt["findings"]:
        h.append(f'<h3>{esc(f["title"])} <span class="packalso">{esc(f["state"])}'
                 + (f' &middot; {esc(f.get("kind", ""))}' if f.get("kind") else '') + '</span></h3>')
        h.append(f'<p class="packdef">{fmt(f.get("note") or f.get("detail") or "")}</p>')
        if f.get("because"):
            h.append(f'<p class="packalso"><b>Accepted because:</b> {fmt(f["because"])}</p>')

    # 6. checks
    h.append('<h2 class="packsec" id="checks">6. What the build checks on every release</h2>')
    h.append('<p>Five rules, each stating itself. A check with zero hits is kept, because a rule '
             'with no hits is still a rule.</p>')
    for c in alt["checks"]:
        h.append(f'<h3>{esc(c["id"])} <span class="packalso">{len(c.get("hits", []))} hits</span></h3>')
        h.append(f'<code class="packrule">{esc(c["rule"])}</code>')
        if c.get("reading"):
            h.append(f'<p class="packdef">{fmt(c["reading"])}</p>')

    # 7. open decisions
    h.append('<h2 class="packsec" id="decisions">7. What is unanswered</h2>')
    h.append(f'<p>{dec["open"]} of {len(dec["decisions"])} decisions are open. Each is the peak of '
             'its own small graph: the options below it, the cost of each option below that, and '
             'the work it blocks out to the side.</p>')
    h.append(figure("decisions.png", "The whole decisions register.",
                    "Purple is a decision, red is a piece of blocked work. Where two decisions "
                    "reach the same block they are one decision raised twice, in two reviews, in "
                    "two vocabularies: four of the twelve blocks are shared that way."))
    for d in dec["decisions"]:
        if d["state"] != "open":
            continue
        h.append(f'<h3>{esc(d["id"])} &middot; {esc(d["short"])}</h3>')
        h.append(f'<p class="packdef">{fmt(d["question"])}</p>')
        if d.get("options"):
            h.append('<table><thead><tr><th>Option</th><th>What it does</th>'
                     '<th>What it costs</th></tr></thead><tbody>')
            for o in d["options"]:
                rec = ' <span class="packpeak">proposed</span>' if o.get("recommended") else ''
                h.append(f'<tr><td><b>{fmt(o["label"])}</b>{rec}</td><td>{fmt(o["does"])}</td>'
                         f'<td>{fmt(o.get("cost", ""))}</td></tr>')
            h.append('</tbody></table>')

    # the asks
    h.append('<h2 class="packsec" id="asks">What this pack is asking you to decide</h2>')
    asks = [
        ("Is this the vocabulary?", "Twenty-four concepts, with their near-but-nots. Which are "
         "missing, which are two ideas wearing one name, and which do not belong in this book at all?"),
        ("Do the peaks match your intent?", "Five were computed. If the ones you would have named "
         "are not there, the formula is wrong, the material is wrong, or the intent has moved. "
         "All three are useful answers and they are different."),
        ("Is concentration telling us something real?", "Only two concepts are genuinely spread "
         "across the corpus. Is that a finding about the corpus, or an artefact of the phrase lists?"),
        ("Which open findings are acceptable in context?", "Three are open. A contradiction that is "
         "correct in context should be marked accepted with its reason, not resolved."),
        ("Any of the ten open decisions you can answer from this?", "The decisions page takes an "
         "answer with a reason and gives you back a block to paste."),
    ]
    for i, (q, why) in enumerate(asks, 1):
        h.append(f'<div class="packask"><b>{i}. {esc(q)}</b>{esc(why)}</div>')

    meta = dict(
        slug="concepts-and-evidence",
        title="The concepts, and what the evidence says about them",
        job="Understand the concepts &middot; see the evidence",
        who="The author, an editor, or a reviewing agent who has read nothing else",
        lead="The vocabulary this book is being built out of, what the twenty-one carried source "
             "documents actually say about it, where the material contradicts itself, and what is "
             "still unanswered. Assembled in one sequence so that none of it depends on clicking "
             "through a website.",
        sources=[("v1/altitudes/data/altitudes.json", alt_sha),
                 ("v1/docs/data/docs.json", docs_sha),
                 ("decisions/data/decisions.json", dec_sha)],
        built="every release",
    )
    return meta, "\n".join(h)


PACKS = [build_concepts_and_evidence]

