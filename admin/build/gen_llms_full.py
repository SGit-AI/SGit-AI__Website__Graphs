#!/usr/bin/env python3
"""Generates llms-full.txt — the whole document set in one fetch.

Run from anywhere: python3 admin/build/gen_llms_full.py

Why this file exists: an agent tried to consume the parent site's documentation and
reported that the index fetch worked and then LINK-FOLLOWING FAILED, because agent fetch
tools refuse URLs a search has not already returned. The conclusion in that report was
that llms.txt "is not a convenience for such agents but the whole surface". The second
mitigation it recommends, after making each llms.txt entry carry a fact rather than a
topic, is to publish a single-file concatenation of the whole document set so that one
fetch gets everything.

This concatenates, in order: llms.txt, the front page's markdown twin, and every source
document under briefs/. It does NOT yet include the prose of the rendered HTML pages —
that is the remaining half, and it is task T6 on the comms board.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
VERSION = (ROOT / "admin/build/version.txt").read_text().strip()

ORDER = [
    "00__BRIEF.md",
    "01__the-thesis.md",
    "02__concepts-index.md",
    "03__worked-examples-index.md",
    "04__visual-assets-and-infographics.md",
    "05__site-architecture.md",
    "06__house-style-and-conventions.md",
    "08__gaps-and-fresh-writing.md",
    "09__licensing-decision.md",
    "00__pack-readme.md",
    "PUBLIC.md",
    "LICENCE.md",
]

HEADER = f"""# graphs.sgit.ai — everything, in one file

Site version: {VERSION}. Generated by admin/build/gen_llms_full.py — do not edit by hand.

This is /llms.txt, then the front page, then all eleven source documents, concatenated in
reading order. It exists because agent fetch tools frequently refuse URLs a search has not
already returned, which makes link-following unreliable and makes a single-file surface the
practical one. If you can make more than one request, prefer the individual documents at
https://graphs.sgit.ai/briefs/<filename> — they are the source of truth and this file is a
concatenation of them.

All content is released under the Creative Commons Attribution 4.0 International licence
(CC BY 4.0). Third-party material quoted inside these documents stays under its own terms.

Contents, in order:
  1. llms.txt — the annotated map, each entry carrying its page's single most important fact
  2. index.md — the front page as markdown
  3–14. the source documents, verbatim, with three redactions recorded in PUBLIC.md

"""

SEP = "\n\n" + "=" * 78 + "\n== {name}\n" + "=" * 78 + "\n\n"


def main():
    parts = [HEADER]
    parts.append(SEP.format(name="llms.txt"))
    parts.append((ROOT / "llms.txt").read_text())
    parts.append(SEP.format(name="index.md — the front page"))
    parts.append((ROOT / "v1/index.md").read_text())
    missing = []
    for name in ORDER:
        p = ROOT / "v1/briefs" / name
        if not p.exists():
            missing.append(name)
            continue
        parts.append(SEP.format(name=f"briefs/{name}"))
        parts.append(p.read_text())
    out = ROOT / "llms-full.txt"
    out.write_text("".join(parts))
    print(f"gen_llms_full: {out.name} — {out.stat().st_size:,} bytes, "
          f"{len(ORDER) - len(missing) + 2} sections")
    for m in missing:
        print(f"  ! briefs/{m} is missing")


if __name__ == "__main__":
    main()
