def fileslug(f):
    return f[:-3].replace("__", "-").replace("_", "-")


def doc_title(path):
    m = re.search(r"^#\s+(.+)$", path.read_text(), re.M)
    return m.group(1).strip() if m else path.name


def render_pack(pack, files, blurbs, packline, statusline, prefix, home):
    """Writes one page per file, chained prev/next within the pack. Returns hub rows."""
    rows = []
    for i, f in enumerate(files):
        slug = (prefix + "-" if prefix else "") + fileslug(f)
        num = f.split("__")[0]
        src = SRC / pack / f
        desc = blurbs[f]
        prev = (f'<a href="{(prefix + "-" if prefix else "") + fileslug(files[i-1])}.html">'
                f'&larr; {files[i-1].split("__")[0]}</a>') if i else f'<a href="{home}">&larr; The pack</a>'
        nxt = (f'<a href="{(prefix + "-" if prefix else "") + fileslug(files[i+1])}.html">'
               f'{files[i+1].split("__")[0]} &rarr;</a>') if i + 1 < len(files) else f'<a href="{home}">The pack &rarr;</a>'
        (OUT / f"{slug}.html").write_text(PAGE.format(
            slug=slug, src=f, pack=pack, num=(prefix + " " if prefix else "") + num,
            title=doc_title(src), desc=desc.replace('"', "&quot;"), gh=GH,
            packline=packline, statusline=statusline, prev=prev, next=nxt))
        rows.append((num, slug, doc_title(src), desc, f))
    return rows


# Three version streams run here: the site's, which moves on every push, and one per book,
# which moves only when that book's content moves. A pack folder therefore has to say WHICH
# stream its number belongs to, or a reader cannot tell whether "v0.6.3" is a site release
# or a book that has no such version. Site packs are `vX.Y.Z__<slug>`; book packs are
# `<book-slug>__vX.Y.Z__<slug>` and declare `book` in the register.
SITE_STAMP = re.compile(r"^v\d+\.\d+\.\d+__")
BOOK_STAMP = re.compile(r"^([a-z0-9-]+)__v(\d+\.\d+\.\d+)__")


def scope_of(spec):
    """(kind, book slug or None, version or None) for a registered pack."""
    d = spec["dir"]
    m = BOOK_STAMP.match(d)
    if m:
        if spec.get("book") != m.group(1):
            raise SystemExit(f'gen_devpack: {d} is stamped for book {m.group(1)!r} but the '
                             f'register says {spec.get("book")!r}')
        return "book", m.group(1), "v" + m.group(2)
    if SITE_STAMP.match(d):
        if spec.get("book"):
            raise SystemExit(f'gen_devpack: {d} declares a book but is stamped as site work')
        return "site", None, d.split("__")[0]
    return "unstamped", None, None


def main():
    OUT.mkdir(exist_ok=True)
    known = {PACK} | {s["dir"] for s in SIDE}
    unknown = [d.name for d in SRC.iterdir() if d.is_dir() and d.name not in known]
    if unknown:
        raise SystemExit("gen_devpack: pack(s) with no registration: " + ", ".join(unknown))

    total = 0
    # the main pack, flat as before
    files = sorted(f.name for f in (SRC / PACK).glob("*.md"))
    missing = [f for f in files if f not in BLURB]
    if missing:
        raise SystemExit("gen_devpack: pack files with no blurb: " + ", ".join(missing))
    total += len(render_pack(PACK, files, BLURB,
                             "v0.4.0 &middot; the second book",
                             "PROPOSED &mdash; nothing here is implemented",
                             "", "index.html"))

    # the working packs, prefixed pages plus generated hub rows
    hub_rows = []
    for s in SIDE:
        files = sorted(f.name for f in (SRC / s["dir"]).glob("*.md"))
        missing = [f for f in files if f not in s["blurbs"]]
        if missing:
            raise SystemExit(f'gen_devpack: {s["dir"]} files with no blurb: ' + ", ".join(missing))
        kind, book, ver = scope_of(s)
        if kind == "book":
            meta = json.loads((ROOT / "v2" / "books" / book / "book.json").read_text())
            # A pack names the version it REVIEWED, which goes historical the moment the
            # book moves. So the stamp must be a version the book has ACTUALLY BEEN AT,
            # not its current one. The first version of this check demanded the current
            # version and fired the moment a book was retitled, which would have meant
            # rewriting the record of a review to match a book it did not review.
            history = [e["version"] for e in meta["changelog"]]
            if ver not in history:
                raise SystemExit(
                    f'gen_devpack: {s["dir"]} is stamped {ver}, which {book} has never '
                    f'been at (it has been at {", ".join(history)})')
            current = ver == meta["version"]
            packline = (f'<b>{meta["title"]}</b> {ver} &middot; {s["packline"]} '
                        f'<span class="small dim">(the book\u2019s version, not the '
                        f'site\u2019s'
                        + ('' if current else f'; the book is now at {meta["version"]}')
                        + ')</span>')
        else:
            packline = s["packline"]
        rows = render_pack(s["dir"], files, s["blurbs"], packline, s["statusline"],
                           s["short"], "index.html#packs")
        total += len(rows)
        for j, (num, slug, title, desc, f) in enumerate(rows):
            hub_rows.append(
                f'      <tr><td>{s["label"] if not j else ""}</td><td class="dpnum">{num}</td>'
                f'<td><a href="{slug}.html"><b>{title}</b></a></td><td>{desc}</td>'
                f'<td><a href="../dev-packs/{s["dir"]}/{f}">.md</a></td></tr>')

    # regenerate the hub's working-packs table between the markers
    t = HUB.read_text()
    if MARK_A not in t or MARK_B not in t:
        raise SystemExit("gen_devpack: the hub has lost its workingpacks markers")
    t = t[:t.index(MARK_A) + len(MARK_A)] + "\n" + "\n".join(hub_rows) + "\n      " + t[t.index(MARK_B):]
    HUB.write_text(t)
    print(f"gen_devpack: {total} page(s) from {1 + len(SIDE)} pack(s) under dev-packs/")


if __name__ == "__main__":
    main()
