/* Generates each operator folder's schema.json and examples.json, plus the
   explorer's manifest (brief 36). Run by gen_wclm.py after the world is
   written: node admin/build/gen_operators.mjs

   schema.json is DERIVED from the operator module's own io declaration, so
   the file can never drift from the code; examples.json is captured by
   actually running the engine through opruntime — the same module the
   workbench's test tab uses — so the vectors are replayable by construction. */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OPS = join(ROOT, 'v2', 'wclm', 'operators');
const { BLOCKS, TYPES } = await import(join(ROOT, 'assets', 'wclm', 'engine.js'));
const { runOperator, prereqOf } = await import(join(ROOT, 'assets', 'wclm', 'opruntime.js'));
const world = JSON.parse(readFileSync(join(ROOT, 'v2', 'wclm', 'data', 'world.json'), 'utf8'));

const folders = readdirSync(OPS).filter((f) => statSync(join(OPS, f)).isDirectory()).sort();
const manifest = { note: 'the operators, each a first-class folder (brief 36); generated by gen_operators.mjs', operators: [] };

for (const key of folders) {
  const block = BLOCKS.find((b) => b.key === key);
  if (!block) throw new Error(`gen_operators: folder ${key} has no registered engine`);
  const mod = await import(join(OPS, key, key + '.js'));
  const ui = mod.ui || { prompts: ['meaning through connectivity'], watch: [] };

  const typed = (list) => list.map((t) => {
    if (!TYPES[t]) throw new Error(`gen_operators: ${key} uses unknown type ${t}`);
    return { type: t, means: TYPES[t] };
  });
  const schema = {
    operator: key, name: block.name, core: !!block.core, role: block.role,
    io: { reads: typed(block.io.reads), writes: typed(block.io.writes) },
    prerequisites: prereqOf(key),
    note: 'derived from ' + key + '.js — the code is the source of truth; a gate re-derives and compares',
  };
  writeFileSync(join(OPS, key, 'schema.json'), JSON.stringify(schema, null, 1) + '\n');

  const vectors = [];
  for (const prompt of ui.prompts || []) {
    const r = runOperator(key, prompt, world, {}, ui.watch);
    vectors.push({ prompt, opts: {}, input: r.input, output: r.output });
  }
  for (const p of ui.presets || []) {
    const r = runOperator(key, (ui.prompts || [''])[0], world, p.opts, ui.watch);
    vectors.push({ prompt: (ui.prompts || [''])[0], label: p.label, opts: p.opts, input: r.input, output: r.output });
  }
  writeFileSync(join(OPS, key, 'examples.json'), JSON.stringify(
    { operator: key, world: world.doc, note: 'captured by running the engine (deterministic); the workbench re-runs and compares', vectors },
    null, 1) + '\n');

  /* the code's own extraction (brief 37): resolve each authored segment's
     head line to a line range, tiling the file completely; drift fails here */
  const anatPath = join(OPS, key, 'anatomy.json');
  const anat = JSON.parse(readFileSync(anatPath, 'utf8'));
  const src = readFileSync(join(OPS, key, key + '.js'), 'utf8').split('\n');
  let cursor = 0;
  anat.segments.forEach((s, i) => {
    let at = -1;
    for (let ln = cursor; ln < src.length; ln++) {
      if (src[ln].trim() === s.head.trim()) { at = ln; break; }
    }
    if (at < 0) throw new Error(`gen_operators: ${key} anatomy segment "${s.id}" — head not found after line ${cursor + 1}: ${s.head}`);
    if (i === 0 && at !== 0) throw new Error(`gen_operators: ${key} anatomy must start at line 1 (segment "${s.id}" resolved to ${at + 1})`);
    if (i > 0) anat.segments[i - 1].lines = [anat.segments[i - 1].lines[0], at];
    s.lines = [at + 1, src.length];
    cursor = at + 1;
  });
  writeFileSync(anatPath, JSON.stringify(anat, null, 1) + '\n');

  const files = readdirSync(join(OPS, key)).sort().map((f) => ({ name: f, bytes: statSync(join(OPS, key, f)).size }));
  manifest.operators.push({ key, name: block.name, role: block.role, core: !!block.core,
    reads: block.io.reads, writes: block.io.writes, files });
}
if (folders.length !== BLOCKS.length) {
  throw new Error(`gen_operators: ${folders.length} folders but ${BLOCKS.length} registered engines`);
}
writeFileSync(join(OPS, 'manifest.json'), JSON.stringify(manifest, null, 1) + '\n');
const nv = manifest.operators.reduce((n, o) => n + o.files.length, 0);
console.log(`gen_operators: ${folders.length} operators — schema + examples + manifest (${nv} files listed)`);
